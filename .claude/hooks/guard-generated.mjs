#!/usr/bin/env node
// PreToolUse hook (Edit|Write|MultiEdit|NotebookEdit): deny hand edits to generated
// files and say which generator owns them. Reads the hook JSON on stdin; prints a
// permissionDecision on stdout. Paths are matched on the absolute file_path, so it
// works in the main checkout and in every worktree.
import { readFileSync } from 'node:fs';

const GENERATED = [
  {
    re: /\/src\/i18n\/lib\/generated\//,
    why: 'src/i18n/lib/generated/* is generated from the catalog. Edit src/i18n/lib/catalog/{tr,en}.json and run `node scripts/gen-keys.mjs`.',
  },
  {
    re: /\/\.expo\/types\//,
    why: '.expo/types/* (typed routes) is regenerated by expo-router when Metro starts. Restart Metro instead of editing it.',
  },
  {
    re: /\/docs\/wellknown\/(apple-app-site-association|assetlinks\.json|assetlinks\.staging\.json)$/,
    why: 'docs/wellknown AASA/assetlinks files are generated. Edit src/lib/deeplinks/paths.json or docs/wellknown/fingerprints.json and run `pnpm wellknown:gen`.',
  },
  {
    re: /\/src\/ui\/icons\/icon-paths\.generated\.ts$/,
    why: 'icon-paths.generated.ts is generated by scripts/gen-icons.mjs from scripts/icon-names.json. Edit the list and rerun the script.',
  },
];

let input = {};
try {
  input = JSON.parse(readFileSync(0, 'utf8') || '{}');
} catch {
  process.exit(0); // unreadable input: no decision, normal permission flow
}
const ti = input.tool_input || {};
const file = String(ti.file_path || ti.notebook_path || '').replace(/\\/g, '/');
const hit = file && GENERATED.find((g) => g.re.test(file));
if (!hit) process.exit(0);

process.stdout.write(
  JSON.stringify({
    hookSpecificOutput: {
      hookEventName: 'PreToolUse',
      permissionDecision: 'deny',
      permissionDecisionReason: `Generated file, do not edit by hand: ${hit.why}`,
    },
  }),
);
